const express = require('express');
const cors = require('cors');
const helmet = require('helmet');
const morgan = require('morgan');
require('dotenv').config();
const sequelize = require('./config/db');
const User = require('./models/User');
const Crop = require('./models/Crop');
const Inventory = require('./models/Inventory');
const Expense = require('./models/Expense');
const Income = require('./models/Income');
const Order = require('./models/Order');
const Task = require('./models/Task');
const Worker = require('./models/Worker');
const Attendance = require('./models/Attendance');
const Equipment = require('./models/Equipment');
const Maintenance = require('./models/Maintenance');
const Buyer = require('./models/Buyer');
const Activity = require('./models/Activity');
const app = express();
app.use(helmet());
app.use(cors({ origin: process.env.FRONTEND_URL, credentials: true }));
app.use(express.json());
app.use(express.urlencoded({ extended: true }));
app.use(morgan('dev'));
app.use('/Images', express.static('public/Images'));
app.get('/', (req, res) => {
  res.json({ message: 'AgriNova Backend Running...' });
});
app.use('/api/users', require('./routes/userRoutes'));
app.use('/api/crops', require('./routes/cropRoutes'));
app.use('/api/orders', require('./routes/orderRoutes'));
app.use('/api/tasks', require('./routes/taskRoutes'));
app.use('/api/expenses', require('./routes/expenseRoutes'));
app.use('/api/inventory', require('./routes/inventoryRoutes'));
app.use('/api/workers', require('./routes/workerRoutes'));
app.use('/api/attendance', require('./routes/attendanceRoutes'));
app.use('/api/equipment', require('./routes/equipmentRoutes'));
app.use('/api/maintenance', require('./routes/maintenanceRoutes'));
app.use('/api/income', require('./routes/incomeRoutes'));
app.use('/api/buyers', require('./routes/buyerRoutes'));
app.use('/api/activities', require('./routes/activityRoutes'));
const PORT = process.env.PORT || 5000;
User.hasMany(Crop, { foreignKey: 'userId' });
Crop.belongsTo(User, { foreignKey: 'userId' });
User.hasMany(Inventory, { foreignKey: 'userId' });
Inventory.belongsTo(User, { foreignKey: 'userId' });
User.hasMany(Expense, { foreignKey: 'userId' });
Expense.belongsTo(User, { foreignKey: 'userId' });
User.hasMany(Income, { foreignKey: 'userId' });
Income.belongsTo(User, { foreignKey: 'userId' });
User.hasMany(Order, { foreignKey: 'userId' });
Order.belongsTo(User, { foreignKey: 'userId' });
User.hasMany(Task, { foreignKey: 'userId' });
Task.belongsTo(User, { foreignKey: 'userId' });
User.hasMany(Worker, { foreignKey: 'userId' });
Worker.belongsTo(User, { foreignKey: 'userId' });
User.hasMany(Attendance, { foreignKey: 'userId' });
Attendance.belongsTo(User, { foreignKey: 'userId' });
User.hasMany(Equipment, { foreignKey: 'userId' });
Equipment.belongsTo(User, { foreignKey: 'userId' });
User.hasMany(Maintenance, { foreignKey: 'userId' });
Maintenance.belongsTo(User, { foreignKey: 'userId' });
User.hasMany(Buyer, { foreignKey: 'userId' });
Buyer.belongsTo(User, { foreignKey: 'userId' });
User.hasMany(Activity, { foreignKey: 'userId' });
Activity.belongsTo(User, { foreignKey: 'userId' });
sequelize.sync({ alter: true })
  .then(() => console.log('DB Connected - Tables Created'))
  .catch(err => console.log('DB Error:', err));
app.listen(PORT, () => {
  console.log(`Server running on port ${PORT}`);
});